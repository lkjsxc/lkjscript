#[cfg(test)]
mod tests {
    use super::*;
    use crate::ContractDescriptor;

    fn digest(descriptor: &ContractDescriptor) -> ContractDigest {
        let result = ContractDigest::of(descriptor);
        assert!(
            result.is_ok(),
            "retained descriptor must encode: {result:?}"
        );
        result.unwrap_or(ContractDigest::from_bytes([0; 32]))
    }

    #[test]
    fn retained_digest_constants_match_canonical_descriptors() {
        let language = digest(&language::language());
        assert_eq!(language, LANGUAGE_DIGEST);
        assert_eq!(digest(&language::source(language)), SOURCE_DIGEST);
        assert_eq!(
            digest(&execution::memory_obligations(language)),
            MEMORY_OBLIGATIONS_DIGEST
        );
        assert_eq!(digest(&execution::metrics()), METRICS_DIGEST);

        let manifest = digest(&platform::package_manifest());
        assert_eq!(manifest, PACKAGE_MANIFEST_DIGEST);
        let module = digest(&platform::module_interface(language));
        assert_eq!(module, MODULE_INTERFACE_DIGEST);
        assert_eq!(
            digest(&platform::package_lock(manifest, module)),
            PACKAGE_LOCK_DIGEST
        );
    }
}
