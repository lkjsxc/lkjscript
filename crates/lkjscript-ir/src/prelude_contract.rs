pub fn option(value: crate::SsaType) -> crate::SsaType {
    crate::SsaType::Enum {
        id: crate::EnumId::new(OPTION_ID),
        arguments: vec![value],
    }
}

pub fn result(ok: crate::SsaType, error: crate::SsaType) -> crate::SsaType {
    crate::SsaType::Enum {
        id: crate::EnumId::new(RESULT_ID),
        arguments: vec![ok, error],
    }
}

pub fn system_result(ok: crate::SsaType) -> crate::SsaType {
    result(
        ok,
        crate::SsaType::Enum {
            id: crate::EnumId::new(SYSTEM_ERROR_ID),
            arguments: Vec::new(),
        },
    )
}
