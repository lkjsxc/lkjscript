const fn stable(a: u64, b: u64, c: u64, d: u64) -> [u8; 32] {
    let parts = [
        a.to_be_bytes(),
        b.to_be_bytes(),
        c.to_be_bytes(),
        d.to_be_bytes(),
    ];
    let mut bytes = [0; 32];
    let mut part = 0;
    while part < 4 {
        let mut index = 0;
        while index < 8 {
            bytes[part * 8 + index] = parts[part][index];
            index += 1;
        }
        part += 1;
    }
    bytes
}

