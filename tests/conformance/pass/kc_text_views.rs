pub fn probe() -> i64 {
    let mut bytes = "a水".bytes();
    assert!(bytes.next().unwrap() == 97u8);
    assert!(bytes.next().unwrap() == 230u8);
    assert!(bytes.next().unwrap() == 176u8);
    assert!(bytes.next().unwrap() == 180u8);
    assert!(bytes.next().is_none());
    let mut chars = "Aé水😀\0\u{10ffff}".chars();
    assert!(chars.next().unwrap() == 'A');
    assert!(chars.next().unwrap() == 'é');
    assert!(chars.next().unwrap() == '水');
    assert!(chars.next().unwrap() == '😀');
    assert!(chars.next().unwrap() == '\0');
    assert!(chars.next().unwrap() == '\u{10ffff}');
    assert!(chars.next().is_none());
    let mut lines = "a\n水\r\n\nz\r".lines();
    let first = lines.next().unwrap();
    let second = lines.next().unwrap();
    assert!(first == "a" && second == "水");
    assert!(lines.next().unwrap() == "");
    assert!(lines.next().unwrap() == "z\r");
    assert!(lines.next().is_none());
    assert!("".lines().next().is_none());
    let mut terminal = "\r\n".lines();
    assert!(terminal.next().unwrap() == "");
    assert!(terminal.next().is_none());
    assert!("水abc".strip_prefix('水').unwrap() == "abc");
    assert!("水abc".strip_prefix("水a").unwrap() == "bc");
    assert!("abc".strip_prefix('x').is_none());
    let pair = "a:水:z".split_once(':').unwrap();
    assert!(pair.0 == "a" && pair.1 == "水:z");
    let mut parts = "::a::::水::".split("::");
    assert!(parts.next().unwrap() == "");
    assert!(parts.next().unwrap() == "a");
    assert!(parts.next().unwrap() == "");
    assert!(parts.next().unwrap() == "水");
    assert!(parts.next().unwrap() == "");
    assert!(parts.next().is_none());
    let mut empty = "é水".split("");
    assert!(empty.next().unwrap() == "");
    assert!(empty.next().unwrap() == "é");
    assert!(empty.next().unwrap() == "水");
    assert!(empty.next().unwrap() == "");
    assert!(empty.next().is_none());
    assert!('\0'.is_control());
    assert!('\u{9f}'.is_control());
    assert!(!'水'.is_control());
    assert!('f'.to_digit(16).unwrap() == 15u32);
    assert!('Z'.to_digit(36).unwrap() == 35u32);
    assert!('g'.to_digit(16).is_none());
    42
}
