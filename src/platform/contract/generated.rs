use super::registry::{
    RegistrySnapshot, contract_descriptors, diagnostic_class_name, diagnostic_descriptors,
    exit_status_descriptors, operation_descriptors, registry_snapshot,
};
use crate::platform::project_creation::ProjectTemplate;
use std::fmt::Write as _;

const GENERATOR_COMMAND: &str = "lkjscript capabilities --generate-docs docs/generated";

#[derive(Clone, Debug)]
pub struct GeneratedDocument {
    pub relative_path: &'static str,
    pub bytes: Vec<u8>,
}

pub fn generated_documents() -> Result<Vec<GeneratedDocument>, String> {
    let snapshot = registry_snapshot()?;
    Ok(vec![
        GeneratedDocument {
            relative_path: "contracts.md",
            bytes: contracts_markdown(&snapshot).into_bytes(),
        },
        GeneratedDocument {
            relative_path: "operations.md",
            bytes: operations_markdown(&snapshot).into_bytes(),
        },
        GeneratedDocument {
            relative_path: "diagnostics.md",
            bytes: diagnostics_markdown(&snapshot).into_bytes(),
        },
    ])
}

fn generated_header(snapshot: &RegistrySnapshot) -> String {
    format!(
        "<!-- Generated by `{GENERATOR_COMMAND}`. Do not edit. Registry `{}`. -->\n\n",
        snapshot.digest
    )
}

fn contracts_markdown(snapshot: &RegistrySnapshot) -> String {
    let mut output = generated_header(snapshot);
    output.push_str("# Current executable contracts\n\n");
    output.push_str("| Key | Identity | Version | Authority | Predecessor |\n");
    output.push_str("|---|---|---:|---|---|\n");
    for contract in contract_descriptors() {
        let _ = writeln!(
            output,
            "| `{}` | `{}` | {} | `{}` | `{}` |",
            contract.key.name(),
            contract.identity,
            contract.version,
            contract.authority.name(),
            contract.predecessor_policy.name()
        );
    }
    output
}

fn operations_markdown(snapshot: &RegistrySnapshot) -> String {
    let mut output = generated_header(snapshot);
    output.push_str("# Public operations\n\n");
    output.push_str("| Operation | Request model | Response model | Authority effect | Usage |\n");
    output.push_str("|---|---|---|---|---|\n");
    for operation in operation_descriptors() {
        let _ = writeln!(
            output,
            "| `{}` | `{}` | `{}` | `{}` | `{}` |",
            operation.operation.name(),
            operation.request_model.name(),
            operation.response_model.name(),
            operation.authority_effect.name(),
            operation.usage
        );
    }
    output.push_str("\n## Project templates\n\n");
    output.push_str(
        "| Template | Purpose | Runner | Starter deployment | Recommended artifact output |\n",
    );
    output.push_str("|---|---|---|---|---|\n");
    for template in ProjectTemplate::ALL {
        let _ = writeln!(
            output,
            "| `{}` | {} | `{}` | `{}` | `{}` |",
            template.name(),
            template.purpose(),
            template.runner(),
            template.emits_deployment(),
            template.recommended_artifact_output().unwrap_or("none")
        );
    }
    output
}

fn diagnostics_markdown(snapshot: &RegistrySnapshot) -> String {
    let mut output = generated_header(snapshot);
    output.push_str("# Protocol diagnostics and exit statuses\n\n");
    output.push_str("| Code | Class | Stable meaning | Retry guidance |\n");
    output.push_str("|---|---|---|---|\n");
    for diagnostic in diagnostic_descriptors() {
        let _ = writeln!(
            output,
            "| `{}` | `{}` | {} | {} |",
            diagnostic.code,
            diagnostic_class_name(diagnostic.class),
            diagnostic.meaning,
            diagnostic.retry
        );
    }
    output.push_str("\n| Exit | Meaning |\n|---:|---|\n");
    for status in exit_status_descriptors() {
        let _ = writeln!(output, "| {} | {} |", status.status, status.meaning);
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_documents_are_unique_and_repeatable() {
        let first = generated_documents().expect("generated documents");
        let second = generated_documents().expect("generated documents");
        assert_eq!(first.len(), 3);
        assert_eq!(first.len(), second.len());
        for (left, right) in first.iter().zip(second.iter()) {
            assert_eq!(left.relative_path, right.relative_path);
            assert_eq!(left.bytes, right.bytes);
            assert!(left.bytes.ends_with(b"\n"));
        }
        let operations = first
            .iter()
            .find(|document| document.relative_path == "operations.md")
            .expect("generated operations document");
        let operations = std::str::from_utf8(&operations.bytes).expect("UTF-8 operations document");
        for template in ProjectTemplate::ALL {
            assert!(operations.contains(&format!("| `{}` |", template.name())));
        }
    }

    #[test]
    fn checked_in_generated_documents_match_executable_truth() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/generated");
        for document in generated_documents().expect("generated documents") {
            let path = root.join(document.relative_path);
            assert_eq!(
                std::fs::read(&path).expect("checked-in generated document"),
                document.bytes,
                "{} is stale; run {GENERATOR_COMMAND}",
                path.display()
            );
        }
        for removed in ["protocol.schema.json", "manifest.json"] {
            assert!(
                !root.join(removed).exists(),
                "obsolete generated JSON must remain deleted"
            );
        }
    }
}
